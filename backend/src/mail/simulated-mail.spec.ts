import { simpleParser } from 'mailparser';
import { describe, expect, it } from 'vitest';
import { isAutoGenerated, stripQuotedText } from './mail-content';
import { buildSimulatedMail, replySubject, replyText, SIMULATED_HEADER } from './simulated-mail';

describe('Simulierte Mails', () => {
  it('baut eine Antwort, die Patchwork wie eine echte zuordnet', async () => {
    const { raw, messageId } = await buildSimulatedMail({
      from: { address: 'anna@firma.ch', name: 'Anna Muster' },
      to: 'helpdesk@firma.ch',
      subject: 'AW: [PW-12] VPN verbindet nicht',
      text: 'Danke, geht wieder.',
      inReplyTo: { messageId: '<pw.2@firma.ch>', references: ['<pw.1@firma.ch>'] },
      attachments: [{ filename: 'log.txt', contentType: 'text/plain', content: Buffer.from('Inhalt') }],
      simulatedBy: 'ada@firma.ch',
    });
    const parsed = await simpleParser(raw);
    expect(parsed.messageId).toBe(messageId);
    expect(parsed.from?.value[0]).toEqual({ address: 'anna@firma.ch', name: 'Anna Muster' });
    expect(parsed.inReplyTo).toBe('<pw.2@firma.ch>');
    expect(parsed.references).toEqual(['<pw.1@firma.ch>', '<pw.2@firma.ch>']);
    expect(parsed.headers.get(SIMULATED_HEADER)).toBe('ada@firma.ch');
    expect(parsed.attachments.map((a) => a.filename)).toEqual(['log.txt']);
    expect(isAutoGenerated(parsed.headers, 'anna@firma.ch')).toBe(false);
  });

  it('kennzeichnet eine Abwesenheitsnotiz wie Outlook', async () => {
    const { raw } = await buildSimulatedMail({
      from: { address: 'anna@firma.ch', name: '' },
      to: 'helpdesk@firma.ch',
      subject: 'Abwesend',
      text: 'Bin in den Ferien.',
      automated: true,
      simulatedBy: 'ada@firma.ch',
    });
    const parsed = await simpleParser(raw);
    expect(isAutoGenerated(parsed.headers, 'anna@firma.ch')).toBe(true);
    expect(parsed.inReplyTo).toBeUndefined();
  });

  it('zitiert die ursprüngliche Mail so, dass Patchwork das Zitat entfernt', () => {
    const text = replyText('Danke, geht wieder.\n\nGruss Anna', {
      from: 'IT Helpdesk <helpdesk@firma.ch>',
      date: new Date('2026-10-20T08:15:00Z'),
      to: ['anna@firma.ch'],
      cc: ['carla@firma.ch'],
      subject: '[PW-12] VPN verbindet nicht',
      text: 'Bitte neu starten.',
    });
    expect(text).toContain('Von: IT Helpdesk <helpdesk@firma.ch>');
    expect(text).toContain('Cc: carla@firma.ch');
    expect(text).toContain('Bitte neu starten.');
    expect(stripQuotedText(text)).toBe('Danke, geht wieder.\n\nGruss Anna');
  });

  it('setzt «AW:» nur einmal vor den Betreff', () => {
    expect(replySubject('[PW-12] VPN')).toBe('AW: [PW-12] VPN');
    expect(replySubject('AW: [PW-12] VPN')).toBe('AW: [PW-12] VPN');
    expect(replySubject('RE: [PW-12] VPN')).toBe('RE: [PW-12] VPN');
  });
});
