const BATCH_SIZE = 50;

function addresses(field: AddressObject | AddressObject[] | undefined): { address: string; name: string }[] {
  const list = Array.isArray(field) ? field : field ? [field] : [];
  return list
    .flatMap((a) => a.value)
    .filter((v) => !!v.address)
    .map((v) => ({ address: v.address!.trim().toLowerCase(), name: v.name?.trim() ?? '' }));
}

function normalizeMessageId(id: string | undefined): string | null {
  const trimmed = id?.trim();
  if (!trimmed) return null;
  return trimmed.startsWith('<') ? trimmed : `<${trimmed}>`;
}

export type IngestResult = 'created' | 'appended' | 'duplicate' | 'ignored';

@Injectable()
export class MailFetcherService implements OnModuleInit {
  private readonly logger = new Logger(MailFetcherService.name);
  private readonly running = new Set<string>();

  constructor(
    @InjectDb() private readonly db: Db,
    private readonly boss: BossService,
    private readonly mailboxes: MailboxesService,
    private readonly transport: MailTransportService,
    private readonly users: UsersService,
    private readonly items: ItemsService,
    private readonly notifications: NotificationsService,
    private readonly storage: StorageService,
    private readonly rules: RulesService,
    private readonly graph: GraphMailService,
  ) {}

  async onModuleInit() {
    await (await this.boss.boss()).work(QUEUE_MAIL_POLL, { batchSize: 1 }, () => this.pollAll());
    if (appConfig.mailPolling) {
      await (await this.boss.boss()).schedule(QUEUE_MAIL_POLL, '* * * * *', {}, { singletonKey: 'poll' });
    } else {
      await (await this.boss.boss()).unschedule(QUEUE_MAIL_POLL);
      this.logger.log('Mail-Abruf ist deaktiviert (MAIL_POLLING=false)');
    }
  }

  async pollAll(): Promise<void> {
    for (const mailbox of await this.mailboxes.list()) {
      if (mailbox.active) await this.poll(mailbox);
    }
  }

  /** Ruft neue Mails eines Postfachs ab. Fehler werden am Postfach vermerkt. */
  async poll(mailbox: Mailbox): Promise<void> {
    // Patchwork läuft als ein Prozess: ein Abruf pro Postfach gleichzeitig
    if (this.running.has(mailbox.id)) return;
    this.running.add(mailbox.id);
    try {
      // Mit angemeldetem Microsoft-Konto über Microsoft Graph, sonst über IMAP
      if (mailbox.authType === 'microsoft') await this.graph.poll(mailbox, (raw) => this.ingest(mailbox, raw));
      else await this.pollUnlocked(mailbox);
    } finally {
      this.running.delete(mailbox.id);
    }
  }

  private async pollUnlocked(mailbox: Mailbox): Promise<void> {
    let client;
    try {
      client = await this.transport.imapClient(mailbox);
      await client.connect();
      // Nur lesend öffnen: Patchwork verändert keine Mails im Postfach (bleiben ungelesen, kein Verschieben)
      const lock = await client.getMailboxLock(mailbox.imapFolder, { readOnly: true });
      try {
        const opened = client.mailbox;
        if (!opened) throw new Error(`Ordner ${mailbox.imapFolder} konnte nicht geöffnet werden`);
        const uidValidity = Number(opened.uidValidity);
        // Erster Abruf, anderer Startzeitpunkt oder neue UIDVALIDITY: Mails ab dem Startzeitpunkt übernehmen,
        // gelesen oder nicht. Danach geht es über die UID weiter, damit nach einem Ausfall nichts fehlt.
        const fresh = mailbox.uidValidity === null || mailbox.uidValidity !== uidValidity;
        // Verarbeitet bis zu dieser UID. Dauert der erste Abruf mehrere Durchgänge, steht hier der Fortschritt
        // (UIDVALIDITY ist dann noch leer). Nach einer neuen UIDVALIDITY gelten die alten UIDs nicht mehr.
        const doneUid = fresh && mailbox.uidValidity !== null ? 0 : mailbox.lastUid;
        const found = fresh
          ? await this.receivedSince(client, mailbox.fetchFrom)
          : await client.search({ uid: `${doneUid + 1}:*` }, { uid: true });
        const pendingUids = (found || []).filter((uid) => uid > doneUid).sort((a, b) => a - b);
        const uids = pendingUids.slice(0, BATCH_SIZE);

        let lastUid = doneUid;
        let error: string | null = null;
        for (const uid of uids) {
          const message = await client.fetchOne(String(uid), { source: true }, { uid: true });
          if (message && message.source) {
            try {
              await this.ingest(mailbox, message.source);
            } catch (err) {
              error = `Mail UID ${uid}: ${(err as Error).message}`;
              this.logger.error(`Verarbeitung von UID ${uid} in ${mailbox.address} fehlgeschlagen`, (err as Error).stack);
            }
          }
          lastUid = Math.max(lastUid, uid);
        }
        if (fresh && pendingUids.length > uids.length) {
          // Noch weitere Mails ab dem Startzeitpunkt: beim nächsten Abruf nach dem Fortschritt weitersuchen
          await this.mailboxes.recordPoll(mailbox.id, { uidValidity: null, lastUid, error });
        } else {
          if (fresh) {
            // Stand beim Öffnen des Ordners merken, damit Mails vor dem Startzeitpunkt nicht übernommen werden
            lastUid = Math.max(lastUid, Number(opened.uidNext) - 1);
          }
          await this.mailboxes.recordPoll(mailbox.id, { uidValidity, lastUid, error });
        }
      } finally {
        lock.release();
      }
      await client.logout();
    } catch (err) {
      const message = explainMailError((err as Error & { responseText?: string }).responseText ?? (err as Error).message, mailbox);
      this.logger.warn(`Abruf von ${mailbox.address} fehlgeschlagen: ${message}`);
      await this.mailboxes.recordPoll(mailbox.id, { error: message });
      client?.close();
    }
  }

  /**
   * UIDs der Mails, die ab dem Zeitpunkt im Ordner eingegangen sind. SINCE kennt nur ganze Tage,
   * deshalb einen Tag Reserve und danach auf die Sekunde genau über den Eingang (INTERNALDATE) filtern.
   */
  private async receivedSince(client: ImapFlow, from: Date): Promise<number[]> {
    const since = new Date(from.getTime() - 24 * 60 * 60 * 1000);
    const start = Math.floor(from.getTime() / 1000) * 1000;
    const uids: number[] = [];
    for await (const message of client.fetch({ since }, { uid: true, internalDate: true }, { uid: true })) {
      const received = message.internalDate ? new Date(message.internalDate).getTime() : NaN;
      // Ohne lesbares Eingangsdatum lieber übernehmen als verlieren
      if (Number.isNaN(received) || received >= start) uids.push(message.uid);
    }
    return uids;
  }

  /** Verarbeitet eine einzelne Mail (Rohdaten). */
  async ingest(mailbox: Mailbox, raw: Buffer): Promise<IngestResult> {
    const parsed = await simpleParser(raw, { skipImageLinks: true, skipTextToHtml: true });
    const from = addresses(parsed.from)[0];
    if (!from) {
      this.logger.warn(`Mail ohne Absender in ${mailbox.address} ignoriert`);
      return 'ignored';
    }
    const own = await this.mailboxes.ownAddresses();
    if (own.has(from.address)) return 'ignored';

    const messageId =
      normalizeMessageId(parsed.messageId) ?? `<sha256.${createHash('sha256').update(raw).digest('hex')}@patchwork>`;
    const [known] = await this.db
      .select({ id: mailMessages.messageId })
      .from(mailMessages)
      .where(eq(mailMessages.messageId, messageId))
      .limit(1);
    if (known) return 'duplicate';

    const automated = isAutoGenerated(parsed.headers, from.address);
    const bulk = isBulk(parsed.headers);
    const ccAddresses = addresses(parsed.cc).filter((a) => !own.has(a.address) && a.address !== from.address);
    const item = await this.findItem(parsed);
    const rawKey = await this.storage.save(raw, 'eml');

    if (item) {
      await this.appendToItem(item, mailbox, parsed, from, ccAddresses, messageId, rawKey, automated);
      return 'appended';
    }
    await this.createItem(mailbox, parsed, from, ccAddresses, messageId, rawKey, automated || bulk);
    return 'created';
  }

  /** Zuordnung über In-Reply-To/References, sonst über die Nummer im Betreff. */
  private async findItem(parsed: ParsedMail): Promise<Item | null> {
    const refs = [
      ...(typeof parsed.inReplyTo === 'string' ? parsed.inReplyTo.split(/\s+/) : []),
      ...(Array.isArray(parsed.references) ? parsed.references : parsed.references ? [parsed.references] : []),
    ]
      .map((r) => normalizeMessageId(r))
      .filter((r): r is string => !!r);
    if (refs.length > 0) {
      const [match] = await this.db
        .select({ item: items })
        .from(mailMessages)
        .innerJoin(items, eq(items.id, mailMessages.itemId))
        .where(inArray(mailMessages.messageId, refs.slice(-50)))
        .limit(1);
      if (match) return this.followDuplicate(match.item);
    }
    const number = extractItemNumber(parsed.subject);
    if (number === null) return null;
    const [byNumber] = await this.db.select().from(items).where(eq(items.number, number)).limit(1);
    return byNumber ? this.followDuplicate(byNumber) : null;
  }

  /** Antworten auf ein umgeleitetes Duplikat gehören zum Original. */
  private async followDuplicate(item: Item): Promise<Item> {
    return (await duplicateRedirect(this.db, item)) ?? item;
  }

  private async createItem(
    mailbox: Mailbox,
    parsed: ParsedMail,
    from: { address: string; name: string },
    cc: { address: string; name: string }[],
    messageId: string,
    rawKey: string,
    suppressConfirmation: boolean,
  ) {
    // Regeln vorab prüfen: Abfragen im Verzeichnis (AD-Gruppen) nicht innerhalb der Transaktion
    const rules = await this.rules.prepare('mail_new', {
      sender: from.address,
      subject: parsed.subject ?? '',
      body: (parsed.text ?? '').trim(),
      mailboxId: mailbox.id,
    });
    const item = await this.db.transaction(async (tx) => {
      const reporter = await this.users.findOrCreateContact(from.address, from.name, tx);
      const [created] = await tx
        .insert(items)
        .values({
          title: (parsed.subject ?? '').trim().slice(0, 500) || '(ohne Betreff)',
          description: (parsed.text ?? '').trim(),
          creatorId: reporter.id,
          reporterId: reporter.id,
          mailboxId: mailbox.id,
          source: 'mail',
        })
        .returning();
      const inlineUrls = await this.saveMailAttachments(tx, created!.id, null, parsed);
      if (parsed.html) {
        await tx
          .update(items)
          .set({ descriptionHtml: sanitizeMailHtml(parsed.html, inlineUrls) })
          .where(eq(items.id, created!.id));
      }
      for (const person of cc) {
        const user = await this.users.findOrCreateContact(person.address, person.name, tx);
        if (user.id !== reporter.id) {
          await tx.insert(participants).values({ itemId: created!.id, userId: user.id }).onConflictDoNothing();
        }
      }
      await tx
        .insert(mailMessages)
        .values({ messageId, itemId: created!.id, direction: 'in', storageKey: rawKey })
        .onConflictDoNothing();
      await rules.apply(tx, created!);
      return created!;
    });
    await rules.afterCommit();
    if (!suppressConfirmation && !rules.suppressConfirmation && !rules.discarded) await this.notifications.confirmation(item);
  }

  private async appendToItem(
    item: Item,
    mailbox: Mailbox,
    parsed: ParsedMail,
    from: { address: string; name: string },
    cc: { address: string; name: string }[],
    messageId: string,
    rawKey: string,
    automated: boolean,
  ) {
    const text = stripQuotedText(parsed.text ?? '');
    let notifyAuthor: User | null = null;
    let notifyItem: Item | null = null;
    // Regeln für Antworten, nicht für Abwesenheitsnotizen und andere automatische Mails
    const rules = automated
      ? null
      : await this.rules.prepare('mail_reply', { sender: from.address, subject: parsed.subject ?? '', body: text, mailboxId: mailbox.id });

    await this.db.transaction(async (tx) => {
      const [locked] = await tx.select().from(items).where(eq(items.id, item.id)).for('update').limit(1);
      if (!locked) return;
      const author = await this.users.findOrCreateContact(from.address, from.name, tx);
      const [participant] = await tx
        .select()
        .from(participants)
        .where(and(eq(participants.itemId, locked.id), eq(participants.userId, author.id)))
        .limit(1);
      const involved = author.id === locked.reporterId || !!participant;

      // Melder und Beteiligte: öffentliche Antwort. Alle anderen (z.B. IT, die auf eine
      // Benachrichtigung antwortet, oder unbeteiligte Dritte): interne Notiz.
      const kind = involved ? 'reply' : 'note';
      const entry = await this.items.addEntry(
        tx,
        locked.id,
        author.id,
        kind,
        text,
        { source: 'mail', subject: parsed.subject ?? '', automated, ...(involved ? {} : { external: true }) },
        { mailMessageId: messageId },
      );
      await this.saveMailAttachments(tx, locked.id, entry.id, parsed);
      await tx
        .insert(mailMessages)
        .values({ messageId, itemId: locked.id, entryId: entry.id, direction: 'in', storageKey: rawKey })
        .onConflictDoNothing();

      if (involved) {
        for (const person of cc) {
          const user = await this.users.findOrCreateContact(person.address, person.name, tx);
          if (user.id !== locked.reporterId) {
            await tx.insert(participants).values({ itemId: locked.id, userId: user.id }).onConflictDoNothing();
          }
        }
      }

      // Antwortpostfach: wenn noch keines gesetzt ist, das Eingangspostfach übernehmen
      await tx
        .update(items)
        .set({ updatedAt: new Date(), ...(locked.mailboxId ? {} : { mailboxId: mailbox.id }) })
        .where(eq(items.id, locked.id));

      if (involved && !automated) {
        await this.items.reopenAfterReply(tx, locked);
        notifyAuthor = author;
        notifyItem = locked;
      }
      await rules?.apply(tx, locked);
    });
    await rules?.afterCommit();

    if (notifyAuthor && notifyItem) await this.notifications.inboundReply(notifyItem, notifyAuthor, text);
  }

  /** Speichert Anhänge einer Mail. Gibt die URLs eingebetteter Bilder (Content-ID → URL) zurück. */
  private async saveMailAttachments(
    tx: Parameters<Parameters<Db['transaction']>[0]>[0],
    itemId: string,
    entryId: string | null,
    parsed: ParsedMail,
  ): Promise<Map<string, string>> {
    const inline = new Map<string, string>();
    for (const att of parsed.attachments) {
      const storageKey = await this.storage.save(att.content);
      const contentId = att.contentId?.replace(/^<|>$/g, '') || null;
      const [row] = await tx
        .insert(attachments)
        .values({
          itemId,
          entryId,
          filename: (att.filename ?? (contentId ? 'bild' : 'anhang')).slice(0, 255),
          contentType: att.contentType || 'application/octet-stream',
          size: att.size ?? att.content.length,
          storageKey,
          contentId: att.related ? contentId : null,
        })
        .returning();
      if (contentId) inline.set(contentId, `/api/attachments/${row!.id}/inline`);
    }
    return inline;
  }
}
