import MarkdownIt from 'markdown-it';
import sanitizeHtml from 'sanitize-html';

import { itemRef, type ItemKey } from '../items/item-ref';

export { itemRef };

/** Betreff mit Kennung, z.B. «[PW-12] Drucker druckt nicht». */
export function subjectFor(item: ItemKey, title: string, label?: string): string {
  return `[${itemRef(item)}] ${label ? `${label}: ` : ''}${title}`;
}

type HeaderValue = unknown;
type Headers = Map<string, HeaderValue>;

function headerText(headers: Headers, name: string): string {
  const value = headers.get(name);
  if (value === undefined || value === null) return '';
  if (typeof value === 'string') return value.toLowerCase();
  if (typeof value === 'object' && 'value' in (value as object)) return String((value as { value: unknown }).value).toLowerCase();
  return String(value).toLowerCase();
}

/** Automatisch erzeugte Mail (Abwesenheitsnotiz, Unzustellbarkeit usw.). Löst keine Bestätigung und keine Statusänderung aus. */
export function isAutoGenerated(headers: Headers, fromAddress: string): boolean {
  const autoSubmitted = headerText(headers, 'auto-submitted');
  if (autoSubmitted && autoSubmitted !== 'no') return true;
  if (headers.has('x-autoreply') || headers.has('x-autorespond')) return true;
  if (['auto_reply', 'auto-reply'].includes(headerText(headers, 'precedence'))) return true;
  if (/^(mailer-daemon|postmaster)@/i.test(fromAddress)) return true;
  const contentType = headerText(headers, 'content-type');
  return contentType.includes('multipart/report');
}

/** Massenmail (Newsletter, Mailingliste). Erhält keine Eingangsbestätigung. */
export function isBulk(headers: Headers): boolean {
  return (
    ['bulk', 'list', 'junk'].includes(headerText(headers, 'precedence')) ||
    // mailparser fasst List-*-Header unter «list» zusammen
    headers.has('list') ||
    headers.has('list-unsubscribe') ||
    headers.has('list-id')
  );
}

const QUOTE_HEADER = [
  /^\s*(Am|On)\s.{4,200}(schrieb|wrote)\b.*:\s*$/i,
  /^\s*-{2,}\s*(Original Message|Ursprüngliche Nachricht|Originalnachricht|Message d'origine)\s*-{2,}/i,
  /^\s*-{2,}\s*(Forwarded message|Weitergeleitete Nachricht)\s*-{2,}/i,
];
const OUTLOOK_FROM = /^\s*\*?(Von|From|De)\s*:\*?\s/i;
const OUTLOOK_FIELDS = /^\s*\*?(Gesendet|Sent|Datum|Date|An|To|Betreff|Subject|Envoyé)\s*:/i;

/** Entfernt zitierte Vorgänger-Nachrichten aus einer Antwort. Liefert den Originaltext, falls nichts übrig bliebe. */
export function stripQuotedText(text: string): string {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  let cut = lines.length;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    const joined = `${line} ${lines[i + 1] ?? ''}`;
    if (QUOTE_HEADER.some((re) => re.test(line))) {
      cut = i;
      break;
    }
    // Gmail bricht «Am …, schrieb X <x@y>:» manchmal auf zwei Zeilen um
    if (/^\s*(Am|On)\s/i.test(line) && QUOTE_HEADER[0]!.test(joined)) {
      cut = i;
      break;
    }
    if (OUTLOOK_FROM.test(line) && lines.slice(i + 1, i + 5).some((l) => OUTLOOK_FIELDS.test(l))) {
      cut = i;
      // Trennlinie direkt davor mit entfernen
      if (i > 0 && /^\s*_{5,}\s*$/.test(lines[i - 1]!)) cut = i - 1;
      break;
    }
  }

  let result = lines.slice(0, cut);
  // Zitatblock mit «>» am Ende entfernen
  let end = result.length;
  while (end > 0 && (/^\s*>/.test(result[end - 1]!) || result[end - 1]!.trim() === '')) end--;
  result = result.slice(0, end);

  const stripped = result.join('\n').trim();
  return stripped || text.trim();
}

const markdown = new MarkdownIt({ html: false, linkify: true, breaks: true });

export function renderMarkdown(source: string): string {
  return markdown.render(source);
}

const escapeHtml = (s: string) =>
  s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** HTML-Gerüst für ausgehende Mails. */
export function htmlMail(bodyHtml: string, footer: string): string {
  return `<!doctype html>
<html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"></head>
<body style="margin:0;padding:24px;font-family:Segoe UI,Helvetica,Arial,sans-serif;font-size:14px;line-height:1.5;color:#1f2328;background:#ffffff">
<div style="max-width:680px">${bodyHtml}</div>
<div style="max-width:680px;margin-top:24px;padding-top:12px;border-top:1px solid #d0d7de;font-size:12px;color:#59636e">${escapeHtml(footer).replace(/\n/g, '<br>')}</div>
</body></html>`;
}

/** Bereinigt HTML aus eingehenden Mails für die Anzeige. Externe Bilder werden entfernt (Tracking). */
/** Marken eingebetteter Bilder im Text einer Mail: Outlook «[cid:…]», Gmail «[image: Name]» (klein geschrieben) */
export function inlineImageMarkers(text: string): { cids: Set<string>; names: Set<string> } {
  return {
    cids: new Set([...text.matchAll(/\[cid:([^\]\s]+)\]/gi)].map((m) => m[1]!.toLowerCase())),
    names: new Set([...text.matchAll(/\[image:\s*([^\]\n]+?)\s*\]/gi)].map((m) => m[1]!.toLowerCase())),
  };
}

/** Steht das eingebettete Bild (Content-ID, Dateiname) mit einer Marke im Text? */
export function hasImageMarker(markers: ReturnType<typeof inlineImageMarkers>, contentId: string, filename: string | null): boolean {
  return markers.cids.has(contentId.toLowerCase()) || (!!filename && markers.names.has(filename.toLowerCase()));
}

/**
 * Ersetzt die Marken eingebetteter Bilder durch Bilder im Text («![Name](attachment:<id>)»), damit sie an ihrer Stelle
 * erscheinen. Bilder ohne Marke bleiben Anhänge.
 */
export function placeInlineImages(text: string, images: { id: string; filename: string; contentId: string | null }[]): string {
  const markdown = (image: { id: string; filename: string }) => `![${image.filename.replace(/[[\]\\]/g, '')}](attachment:${image.id})`;
  const withCid = images.filter((i) => i.contentId);
  return text
    .replace(/\[cid:([^\]\s]+)\]/gi, (all, cid: string) => {
      const image = withCid.find((i) => i.contentId!.toLowerCase() === cid.toLowerCase());
      return image ? markdown(image) : all;
    })
    .replace(/\[image:\s*([^\]\n]+?)\s*\]/gi, (all, name: string) => {
      const image = withCid.find((i) => i.filename.toLowerCase() === name.toLowerCase());
      return image ? markdown(image) : all;
    });
}

export function sanitizeMailHtml(html: string, inlineUrls: Map<string, string>): string {
  return sanitizeHtml(html, {
    allowedTags: [
      ...sanitizeHtml.defaults.allowedTags,
      'img',
      'span',
      'font',
      'center',
      'del',
      'ins',
      'u',
      's',
    ],
    allowedAttributes: {
      a: ['href', 'title'],
      img: ['src', 'alt', 'width', 'height'],
      td: ['colspan', 'rowspan', 'align', 'valign'],
      th: ['colspan', 'rowspan', 'align', 'valign'],
      table: ['border', 'cellpadding', 'cellspacing'],
      '*': ['align'],
    },
    allowedSchemes: ['http', 'https', 'mailto', 'tel'],
    allowProtocolRelative: false,
    transformTags: {
      a: (tagName, attribs) => ({
        tagName,
        attribs: { ...attribs, target: '_blank', rel: 'noopener noreferrer nofollow' },
      }),
      img: (tagName, attribs) => {
        const src = attribs.src ?? '';
        if (src.toLowerCase().startsWith('cid:')) {
          const url = inlineUrls.get(src.slice(4).replace(/^<|>$/g, ''));
          // Ohne passenden Anhang: Bild ohne Adresse, fällt unten ganz weg
          return url ? { tagName, attribs: { ...attribs, src: url } } : { tagName, attribs: {} };
        }
        if (/^data:image\/(png|jpe?g|gif|webp);/i.test(src)) return { tagName, attribs };
        return { tagName, attribs: {} };
      },
    },
    // img-src wird oben in transformTags geprüft (nur eingebettete Bilder und data:-Bilder)
    allowedSchemesAppliedToAttributes: ['href', 'cite'],
    // Nur entfernte Bilder (ohne Adresse) fallen weg; ein leeres <span> um ein Bild (bei Outlook häufig) bleibt samt Bild
    exclusiveFilter: (frame) => frame.tag === 'img' && !frame.attribs.src,
  });
}
