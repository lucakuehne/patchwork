import { describe, expect, it } from 'vitest';
import { itemKeyFromSubject } from '../items/item-ref';
import {
  hasImageMarker,
  inlineImageMarkers,
  isAutoGenerated,
  isBulk,
  placeInlineImages,
  sanitizeMailHtml,
  stripQuotedText,
  subjectFor,
} from './mail-content';

describe('Betreff', () => {
  it('erzeugt und erkennt die Kennung', () => {
    expect(subjectFor({ prefix: 'PW', number: 12 }, 'Drucker druckt nicht')).toBe('[PW-12] Drucker druckt nicht');
    expect(subjectFor({ prefix: 'PW', number: 12 }, 'Drucker', 'Erledigt')).toBe('[PW-12] Erledigt: Drucker');
    expect(subjectFor({ prefix: 'HS', number: 17223 }, 'Alt')).toBe('[HS-17223] Alt');
    expect(itemKeyFromSubject('AW: [PW-1234] VPN')).toEqual({ prefix: 'PW', number: 1234 });
    expect(itemKeyFromSubject('Re: [pw-7] klein')).toEqual({ prefix: 'PW', number: 7 });
    expect(itemKeyFromSubject('PW-12 ohne Klammern')).toBeNull();
  });
});

describe('stripQuotedText', () => {
  it('schneidet beim Gmail-Zitatkopf ab', () => {
    const text = 'Danke, geht wieder.\n\nAm Mi., 15. Okt. 2026 um 10:00 Uhr schrieb IT <it@firma.ch>:\n> Bitte neu starten';
    expect(stripQuotedText(text)).toBe('Danke, geht wieder.');
  });

  it('erkennt umgebrochene Zitatköpfe', () => {
    const text = 'Ok.\n\nOn Wed, Oct 15, 2026 at 10:00 AM IT Support <\nit@firma.ch> wrote:\n> alt';
    expect(stripQuotedText(text)).toBe('Ok.');
  });

  it('schneidet beim Outlook-Kopf ab', () => {
    const text = 'Passt.\n\n________________________________\nVon: IT <it@firma.ch>\nGesendet: Mittwoch\nAn: Anna\nBetreff: [PW-1] Test\n\nalt';
    expect(stripQuotedText(text)).toBe('Passt.');
  });

  it('entfernt Zitatblöcke am Ende', () => {
    expect(stripQuotedText('Ja\n> vorher\n> mehr')).toBe('Ja');
  });

  it('liefert den Originaltext, wenn nur Zitat übrig bliebe', () => {
    expect(stripQuotedText('> nur zitat')).toBe('> nur zitat');
  });
});

describe('Header-Erkennung', () => {
  const h = (entries: [string, unknown][]) => new Map(entries);

  it('erkennt Autoantworten', () => {
    expect(isAutoGenerated(h([['auto-submitted', 'auto-replied']]), 'a@b.ch')).toBe(true);
    expect(isAutoGenerated(h([['auto-submitted', 'no']]), 'a@b.ch')).toBe(false);
    expect(isAutoGenerated(h([['x-autoreply', 'yes']]), 'a@b.ch')).toBe(true);
    expect(isAutoGenerated(h([]), 'MAILER-DAEMON@b.ch')).toBe(true);
    expect(isAutoGenerated(h([['content-type', { value: 'multipart/report' }]]), 'a@b.ch')).toBe(true);
    expect(isAutoGenerated(h([]), 'anna@firma.ch')).toBe(false);
  });

  it('erkennt Massenmails', () => {
    expect(isBulk(h([['precedence', 'bulk']]))).toBe(true);
    expect(isBulk(h([['list-unsubscribe', '<mailto:x>']]))).toBe(true);
    expect(isBulk(h([['list', { unsubscribe: { mail: 'x@y' } }]]))).toBe(true);
    expect(isBulk(h([]))).toBe(false);
  });
});

describe('Eingebettete Bilder im Text', () => {
  const images = [
    { id: 'a1', filename: 'image001.png', contentId: 'image001.png@01DC' },
    { id: 'a2', filename: 'Screenshot [1].png', contentId: 'ii_xyz' },
    { id: 'a3', filename: 'Beilage.pdf', contentId: null },
  ];

  it('erkennt Marken von Outlook und Gmail', () => {
    const markers = inlineImageMarkers('Hallo\n[cid:IMAGE001.png@01DC]\n[image: Screenshot.png]');
    expect([...markers.cids]).toEqual(['image001.png@01dc']);
    expect([...markers.names]).toEqual(['screenshot.png']);
    expect(hasImageMarker(markers, 'image001.png@01DC', null)).toBe(true);
    expect(hasImageMarker(markers, 'andere@1', 'screenshot.PNG')).toBe(true);
    expect(hasImageMarker(markers, 'andere@1', 'logo.png')).toBe(false);
  });

  it('setzt die Bilder an die Stelle der Marke, unbekannte Marken bleiben', () => {
    expect(placeInlineImages('Siehe:\n[cid:image001.png@01DC]\nGruss [cid:fremd@1]', images)).toBe(
      'Siehe:\n![image001.png](attachment:a1)\nGruss [cid:fremd@1]',
    );
    expect(placeInlineImages('[image: Screenshot [1].png]', images)).toBe('[image: Screenshot [1].png]');
    expect(placeInlineImages('[image: screenshot 1.png]', [{ id: 'b', filename: 'Screenshot 1.png', contentId: 'x' }])).toBe(
      '![Screenshot 1.png](attachment:b)',
    );
    // Echte Anhänge (ohne Content-ID) werden nicht eingesetzt
    expect(placeInlineImages('[image: Beilage.pdf]', images)).toBe('[image: Beilage.pdf]');
  });
});

describe('sanitizeMailHtml', () => {
  it('entfernt Skripte, Styles und externe Bilder, ersetzt cid-Bilder', () => {
    const html =
      '<p style="color:red" onclick="x()">Hallo<script>alert(1)</script></p><img src="https://tracker/x.gif"><img src="cid:abc@1"><a href="javascript:alert(1)">x</a>';
    const out = sanitizeMailHtml(html, new Map([['abc@1', '/api/attachments/1/inline']]));
    expect(out).toContain('<p>Hallo</p>');
    expect(out).not.toContain('script');
    expect(out).not.toContain('tracker');
    expect(out).toContain('src="/api/attachments/1/inline"');
    expect(out).not.toContain('javascript');
    expect(out.match(/<img/g)).toHaveLength(1);
  });

  it('behält eingebettete Bilder in einem leeren <span> (Outlook mit VML)', () => {
    const html =
      '<p><span><!--[if gte vml 1]><v:shape id="G"><v:imagedata src="cid:image001.png@01DC" o:title=""/></v:shape><![endif]-->' +
      '<![if !vml]><span style="mso-ignore:vglayout"><img width="50" height="50" src="cid:image001.png@01DC" v:shapes="G"></span><![endif]></span></p>';
    const out = sanitizeMailHtml(html, new Map([['image001.png@01DC', '/api/attachments/7/inline']]));
    expect(out).toContain('<img width="50" height="50" src="/api/attachments/7/inline" />');
    expect(out.match(/<img/g)).toHaveLength(1);
    // Ohne passenden Anhang fällt das Bild weg, ohne Reste
    expect(sanitizeMailHtml('<p>Text<span><img src="cid:fehlt@1"></span></p>', new Map())).toBe('<p>Text<span></span></p>');
  });
});
